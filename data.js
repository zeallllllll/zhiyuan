function formatScoreValue(v) {
  if (v == null) return null;
  return Number(v).toFixed(1).replace(/\.0$/, "");
}

function logoTextFor(name) {
  const prefixes = ["上海市", "上海", "复旦大学", "华东师范大学", "上海交通大学", "上海财经大学", "上海师范大学"];
  let text = name;
  for (const prefix of prefixes) {
    if (text.startsWith(prefix)) {
      text = text.slice(prefix.length);
      break;
    }
  }
  return text.slice(0, 1);
}

function tagsFor(score2025) {
  if (score2025 >= 750) {
    return [
      { label: "名额到区", kind: "purple" },
      { label: "750+高分段", kind: "orange" },
    ];
  }
  if (score2025 >= 735) {
    return [
      { label: "名额到区", kind: "blue" },
      { label: "735+高分段", kind: "teal" },
    ];
  }
  return [{ label: "名额到区", kind: "blue" }];
}

